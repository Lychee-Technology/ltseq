"""Tables from ``run.py``'s results: ``python benchmarks/m0/report.py``.

Writes ``results/<name>.md`` next to each ``results/<name>.json``: one row
per cell, with the median of its measured runs, the ratio to the baseline
mode of the same scenario (same pipeline, terminal, input and partition
count), throughput over the input rows, the first run's peak memory and,
for streamed terminals, its time to first row. A cell during which other
processes kept more than ``CONTENDED`` cores busy is flagged in its note.
"""

from __future__ import annotations

import argparse
import json
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"

# The mode every other mode of a measurement is compared with.
BASELINE = {"m1": "off", "m2": "off", "m3": "off", "m4": "today", "m4b": "pushdown", "m5": "off", "m6": "off"}

# Cores other processes may keep busy, averaged over a cell, before the
# cell is flagged as contended.
CONTENDED = 0.5


def summarize(cell: dict) -> dict:
    result = cell["result"]
    runs = result.get("runs") or []
    out = {"error": result.get("error"), "aborted": result.get("aborted", False),
           "other_cores": result.get("other_cores")}
    if runs:
        seconds = [r["seconds"] for r in runs]
        out["median"] = statistics.median(seconds)
        out["first"] = seconds[0]
        out["min"] = min(seconds)
        out["peak_mib"] = runs[0]["peak_above"] / 2**20
        ttfrs = [r["ttfr"] for r in runs if r.get("ttfr") is not None]
        out["ttfr_ms"] = statistics.median(ttfrs) * 1000 if ttfrs else None
        out["rows_out"] = runs[0].get("rows_out")
        rows_in = cell["input"].get("rows")
        out["mrows_s"] = rows_in / out["median"] / 1e6 if rows_in else None
    elif result.get("aborted"):
        out["peak_mib"] = (result.get("peak_above") or 0) / 2**20
    return out


def scenario(cell: dict) -> tuple:
    labels = {k: v for k, v in cell["labels"].items() if k != "mode"}
    return (cell["pipeline"], cell["terminal"], cell["partitions"], tuple(sorted(labels.items())))


def fmt(value, spec: str) -> str:
    return "" if value is None else format(value, spec)


def table(record: dict) -> str:
    name = record["measurement"]
    base_mode = BASELINE[name]
    cells = record["cells"]
    baselines = {}
    for cell in cells:
        if cell["labels"].get("mode") == base_mode:
            baselines[scenario(cell)] = summarize(cell)
    label_keys = [k for k in cells[0]["labels"] if k != "mode"] if cells else []
    head = ["pipeline", "terminal", *label_keys, "p", "mode", "median s", "× " + base_mode, "first s",
            "Mrows/s", "peak MiB", "TTFR ms", "note"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for cell in cells:
        s = summarize(cell)
        base = baselines.get(scenario(cell), {})
        ratio = s["median"] / base["median"] if s.get("median") and base.get("median") else None
        note = ""
        if (s["other_cores"] or 0) > CONTENDED:
            note = f"contended ({s['other_cores']:.1f} other cores) "
        if s["aborted"]:
            note += "aborted: " + (s["error"] or "memory")
        elif s["error"]:
            note += s["error"].split("\n")[0][:90].replace("|", "/")
        row = [
            cell["pipeline"],
            cell["terminal"],
            *[str(cell["labels"].get(k, "")) for k in label_keys],
            str(cell["partitions"]),
            str(cell["labels"].get("mode", "")),
            fmt(s.get("median"), ".4f"),
            fmt(ratio, ".2f"),
            fmt(s.get("first"), ".4f"),
            fmt(s.get("mrows_s"), ".1f"),
            fmt(s.get("peak_mib"), ".1f"),
            fmt(s.get("ttfr_ms"), ".1f"),
            note,
        ]
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def document(record: dict) -> str:
    host = record["host"]
    build = ", ".join(f"{k}={v}" for k, v in host.get("m0_build", {}).items())
    others = [c["result"].get("other_cores") for c in record["cells"]]
    measured = [o for o in others if o is not None]
    contended = sum(o > CONTENDED for o in measured)
    return "\n".join([
        f"# {record['measurement']}: {record['title']}",
        "",
        f"Gates: {record['gates']}. Generated by `report.py` from `{record['measurement']}.json`.",
        "",
        f"- Commit `{host['commit']}`{' (with uncommitted changes)' if host['worktree_dirty'] else ''}, "
        f"branch `{host['branch']}`",
        f"- {host['cpu']}, {host['cpu_count']} CPUs, {host['memory_bytes'] / 2**30:.1f} GiB, "
        f"Linux {host['kernel']}",
        f"- Python {host['python']}, pyarrow {host['pyarrow']}, {host['rustc']}; m0 build: {build}",
        f"- Command: `{host['command']}`, started {host['started']}",
        f"- Contention: {contended} of {len(measured)} cells ran while other processes kept more than "
        f"{CONTENDED} cores busy (flagged in the note)" if measured else "- Contention: not recorded",
        "",
        "`median s` is the median of a cell's measured runs (plan building plus the terminal); "
        "`first s` is the first measured run, which also reads metadata later runs find cached "
        "(a Parquet footer); `peak MiB` is the first measured run's resident growth; `TTFR ms` is "
        "the time to the first non-empty batch of a stream.",
        "",
        table(record),
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", help="measurements (comma-separated); default every results file")
    parser.add_argument("--dir", type=Path, default=RESULTS)
    args = parser.parse_args()
    names = args.only.split(",") if args.only else sorted(p.stem for p in args.dir.glob("*.json"))
    for name in names:
        record = json.loads((args.dir / f"{name}.json").read_text())
        target = args.dir / f"{name}.md"
        target.write_text(document(record))
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
